import { Base2DVisualizer } from '../base/Base2DVisualizer'
import { VisualizerRenderContext } from '../types'

interface RadarBlip {
  x: number
  y: number
  radius: number
  opacity: number
  color: string
}

export class AudioRadarVisualizer extends Base2DVisualizer {
  public readonly id = 'audio-radar'
  public readonly name = 'Audio Radar'
  public readonly category = 'Circular'
  public readonly description = 'Tactical radar sonar sweep displaying persistent audio blips and frequency arcs'

  private sweepAngle: number = 0
  private blips: RadarBlip[] = []

  public render(context: VisualizerRenderContext): void {
    const { ctx2d, config, audioFrame, width, height } = context
    if (!ctx2d) return

    ctx2d.save()
    this.applyTransform(ctx2d, context)

    const radarRadius = Math.min(width, height) * 0.22
    const { bassEnergy, overallEnergy } = audioFrame
    const freqs = audioFrame.normalizedFrequencies

    this.applyGlow(ctx2d, config.accentColor, config.glow, bassEnergy)

    // Advance radar sweep angle
    const sweepSpeed = 0.035 + overallEnergy * 0.02
    this.sweepAngle = (this.sweepAngle + sweepSpeed) % (Math.PI * 2)

    // Check if new blips should be generated by audio peaks swept by beam
    const sampleBin = Math.floor((this.sweepAngle / (Math.PI * 2)) * 128)
    const currentMag = (freqs[sampleBin] || 0) * config.sensitivity

    if (currentMag > 0.25) {
      // Distance from center mapped to frequency / magnitude
      const dist = radarRadius * (0.2 + (sampleBin / 128) * 0.75)
      const bx = Math.cos(this.sweepAngle) * dist
      const by = Math.sin(this.sweepAngle) * dist
      this.blips.push({
        x: bx,
        y: by,
        radius: 3 + currentMag * 8,
        opacity: 1.0,
        color: currentMag > 0.6 ? config.accentColor : config.primaryColor,
      })
    }

    // Limit blips
    if (this.blips.length > 50) {
      this.blips.shift()
    }

    // 1. Concentric Range Rings
    const ringCount = 5
    for (let r = 1; r <= ringCount; r++) {
      const radius = (radarRadius / ringCount) * r
      ctx2d.strokeStyle =
        r === ringCount ? `${config.primaryColor}80` : `${config.primaryColor}30`
      ctx2d.lineWidth = r === ringCount ? 2 : 1
      ctx2d.beginPath()
      ctx2d.arc(0, 0, radius, 0, Math.PI * 2)
      ctx2d.stroke()

      // Distance markers
      ctx2d.font = '9px JetBrains Mono, monospace'
      ctx2d.fillStyle = `${config.primaryColor}60`
      ctx2d.fillText(`${r * 20}%`, 4, -radius + 10)
    }

    // 2. Crosshair Grid Lines
    ctx2d.strokeStyle = `${config.primaryColor}30`
    ctx2d.lineWidth = 1
    ctx2d.beginPath()
    ctx2d.moveTo(-radarRadius, 0)
    ctx2d.lineTo(radarRadius, 0)
    ctx2d.moveTo(0, -radarRadius)
    ctx2d.lineTo(0, radarRadius)
    ctx2d.stroke()

    // 3. Rotating Radar Sweep Sector (gradient fan)
    const sweepArc = Math.PI * 0.35 // 60-degree sweep fan
    const fanSegments = 16
    for (let s = 0; s < fanSegments; s++) {
      const startA = this.sweepAngle - (sweepArc / fanSegments) * (s + 1)
      const endA = this.sweepAngle - (sweepArc / fanSegments) * s
      const alpha = (1 - s / fanSegments) * 0.25

      ctx2d.fillStyle = `${config.accentColor}${Math.floor(alpha * 255)
        .toString(16)
        .padStart(2, '0')}`
      ctx2d.beginPath()
      ctx2d.moveTo(0, 0)
      ctx2d.arc(0, 0, radarRadius, startA, endA)
      ctx2d.closePath()
      ctx2d.fill()
    }

    // 4. Leading Sweep Beam
    ctx2d.strokeStyle = '#ffffff'
    ctx2d.lineWidth = 2
    ctx2d.beginPath()
    ctx2d.moveTo(0, 0)
    ctx2d.lineTo(
      Math.cos(this.sweepAngle) * radarRadius,
      Math.sin(this.sweepAngle) * radarRadius
    )
    ctx2d.stroke()

    // 5. Render & Decay Persistent Blips
    for (let i = this.blips.length - 1; i >= 0; i--) {
      const blip = this.blips[i]
      ctx2d.fillStyle = blip.color
      ctx2d.globalAlpha = blip.opacity * config.opacity

      ctx2d.beginPath()
      ctx2d.arc(blip.x, blip.y, blip.radius, 0, Math.PI * 2)
      ctx2d.fill()

      // Pulse ring around fresh blip
      if (blip.opacity > 0.7) {
        ctx2d.strokeStyle = blip.color
        ctx2d.lineWidth = 1
        ctx2d.beginPath()
        ctx2d.arc(blip.x, blip.y, blip.radius * 2, 0, Math.PI * 2)
        ctx2d.stroke()
      }

      // Decay blip
      blip.opacity -= 0.015
      if (blip.opacity <= 0) {
        this.blips.splice(i, 1)
      }
    }

    // 6. Outer Frequency Perimeter Arcs
    const arcCount = 32
    const arcStep = (Math.PI * 2) / arcCount
    for (let a = 0; a < arcCount; a++) {
      const angle = a * arcStep
      const binIdx = Math.floor((a / arcCount) * 128)
      const mag = (freqs[binIdx] || 0) * config.sensitivity
      const arcLen = mag * 16

      if (arcLen > 2) {
        ctx2d.strokeStyle = config.accentColor
        ctx2d.lineWidth = 3
        ctx2d.beginPath()
        ctx2d.arc(0, 0, radarRadius + 6, angle, angle + arcStep * 0.7)
        ctx2d.stroke()
      }
    }

    ctx2d.restore()
  }

  public override dispose(): void {
    this.blips = []
  }
}
